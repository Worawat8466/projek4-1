ALTER TABLE staff ADD (
  recovery_code_hash VARCHAR2(255),
  recovery_used_at TIMESTAMP WITH TIME ZONE
);

CREATE TABLE auth_sessions (
  session_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  staff_id NUMBER NOT NULL REFERENCES staff(staff_id) ON DELETE CASCADE,
  token_hash VARCHAR2(64) NOT NULL UNIQUE,
  expires_at TIMESTAMP WITH TIME ZONE NOT NULL,
  created_at TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL
);

CREATE INDEX ix_auth_sessions_staff ON auth_sessions(staff_id);