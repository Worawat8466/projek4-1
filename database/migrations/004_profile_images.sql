CREATE TABLE profile_images (
  profile_image_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  customer_id NUMBER UNIQUE REFERENCES customers(customer_id) ON DELETE CASCADE,
  pet_id NUMBER UNIQUE REFERENCES pets(pet_id) ON DELETE CASCADE,
  staff_id NUMBER UNIQUE REFERENCES staff(staff_id) ON DELETE CASCADE,
  mime_type VARCHAR2(40) NOT NULL CHECK (mime_type IN ('image/jpeg', 'image/png', 'image/webp')),
  file_name VARCHAR2(255) NOT NULL,
  file_size NUMBER(10) NOT NULL CHECK (file_size > 0 AND file_size <= 5242880),
  image_data BLOB NOT NULL,
  created_at TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  updated_at TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT ck_profile_images_owner CHECK (
    (customer_id IS NOT NULL AND pet_id IS NULL AND staff_id IS NULL) OR
    (customer_id IS NULL AND pet_id IS NOT NULL AND staff_id IS NULL) OR
    (customer_id IS NULL AND pet_id IS NULL AND staff_id IS NOT NULL)
  )
);