CREATE TABLE app_notifications (
  notification_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  notification_key VARCHAR2(240) NOT NULL UNIQUE,
  notification_type VARCHAR2(30) NOT NULL,
  severity VARCHAR2(20) NOT NULL CHECK (severity IN ('info', 'warning', 'critical')),
  title VARCHAR2(200) NOT NULL,
  message VARCHAR2(500) NOT NULL,
  action_href VARCHAR2(200) NOT NULL,
  is_active CHAR(1) DEFAULT 'Y' NOT NULL CHECK (is_active IN ('Y', 'N')),
  created_at TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  updated_at TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL
);

CREATE TABLE notification_reads (
  notification_id NUMBER NOT NULL REFERENCES app_notifications(notification_id) ON DELETE CASCADE,
  reader_key VARCHAR2(80) NOT NULL,
  read_at TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT pk_notification_reads PRIMARY KEY (notification_id, reader_key)
);

CREATE INDEX ix_app_notifications_active ON app_notifications(is_active, updated_at);