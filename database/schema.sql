-- Oracle Database 19c+ schema for TleClinic POS.
-- Run once in the target schema using SQL Developer or SQLcl.

CREATE TABLE staff_roles (
  role_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  role_code VARCHAR2(30) NOT NULL UNIQUE,
  role_name VARCHAR2(100) NOT NULL,
  permissions_json CLOB,
  is_system CHAR(1) DEFAULT 'N' NOT NULL CHECK (is_system IN ('Y', 'N')),
  created_at TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL
);

CREATE TABLE staff (
  staff_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  role_id NUMBER NOT NULL REFERENCES staff_roles(role_id),
  first_name VARCHAR2(100) NOT NULL,
  last_name VARCHAR2(100) NOT NULL,
  email VARCHAR2(254) NOT NULL UNIQUE,
  phone VARCHAR2(30),
  password_hash VARCHAR2(255),
  pin_hash VARCHAR2(255),
  is_active CHAR(1) DEFAULT 'Y' NOT NULL CHECK (is_active IN ('Y', 'N')),
  last_login_at TIMESTAMP WITH TIME ZONE,
  created_at TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  updated_at TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL
);

CREATE TABLE customers (
  customer_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  customer_code VARCHAR2(40) NOT NULL UNIQUE,
  first_name VARCHAR2(100) NOT NULL,
  last_name VARCHAR2(100),
  phone VARCHAR2(30),
  email VARCHAR2(254),
  address VARCHAR2(1000),
  is_active CHAR(1) DEFAULT 'Y' NOT NULL CHECK (is_active IN ('Y', 'N')),
  created_at TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  updated_at TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL
);

CREATE TABLE pets (
  pet_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  customer_id NUMBER NOT NULL REFERENCES customers(customer_id),
  pet_name VARCHAR2(100) NOT NULL,
  species VARCHAR2(40) NOT NULL,
  breed VARCHAR2(100),
  sex VARCHAR2(10) CHECK (sex IN ('MALE', 'FEMALE', 'UNKNOWN')),
  birth_date DATE,
  chip_number VARCHAR2(80) UNIQUE,
  notes VARCHAR2(2000),
  is_active CHAR(1) DEFAULT 'Y' NOT NULL CHECK (is_active IN ('Y', 'N')),
  created_at TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  updated_at TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL
);

CREATE TABLE product_categories (
  category_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  parent_category_id NUMBER REFERENCES product_categories(category_id),
  category_name VARCHAR2(100) NOT NULL,
  is_active CHAR(1) DEFAULT 'Y' NOT NULL CHECK (is_active IN ('Y', 'N')),
  created_at TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL
);

CREATE TABLE products (
  product_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  category_id NUMBER REFERENCES product_categories(category_id),
  product_code VARCHAR2(80) NOT NULL UNIQUE,
  barcode VARCHAR2(100) UNIQUE,
  product_name VARCHAR2(200) NOT NULL,
  product_type VARCHAR2(20) NOT NULL CHECK (product_type IN ('PRODUCT', 'SERVICE')),
  base_unit VARCHAR2(40) NOT NULL,
  base_sale_price NUMBER(12, 2) DEFAULT 0 NOT NULL CHECK (base_sale_price >= 0),
  base_cost NUMBER(12, 4) CHECK (base_cost >= 0),
  min_stock NUMBER(14, 3) DEFAULT 0 NOT NULL CHECK (min_stock >= 0),
  tracks_stock CHAR(1) DEFAULT 'Y' NOT NULL CHECK (tracks_stock IN ('Y', 'N')),
  is_active CHAR(1) DEFAULT 'Y' NOT NULL CHECK (is_active IN ('Y', 'N')),
  created_at TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  updated_at TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL
);

CREATE TABLE product_units (
  unit_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  product_id NUMBER NOT NULL REFERENCES products(product_id),
  unit_name VARCHAR2(40) NOT NULL,
  base_units_per_unit NUMBER(14, 4) NOT NULL CHECK (base_units_per_unit > 0),
  sale_price NUMBER(12, 2) NOT NULL CHECK (sale_price >= 0),
  is_default_sale_unit CHAR(1) DEFAULT 'N' NOT NULL CHECK (is_default_sale_unit IN ('Y', 'N')),
  CONSTRAINT uq_product_unit UNIQUE (product_id, unit_name)
);

CREATE TABLE suppliers (
  supplier_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  supplier_code VARCHAR2(40) NOT NULL UNIQUE,
  company_name VARCHAR2(200) NOT NULL,
  contact_name VARCHAR2(150),
  phone VARCHAR2(30),
  email VARCHAR2(254),
  address VARCHAR2(1000),
  is_active CHAR(1) DEFAULT 'Y' NOT NULL CHECK (is_active IN ('Y', 'N')),
  created_at TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  updated_at TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL
);

CREATE TABLE purchase_orders (
  purchase_order_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  po_number VARCHAR2(40) NOT NULL UNIQUE,
  supplier_id NUMBER NOT NULL REFERENCES suppliers(supplier_id),
  status VARCHAR2(20) DEFAULT 'ORDERED' NOT NULL CHECK (status IN ('ORDERED', 'PARTIAL', 'RECEIVED', 'CANCELLED')),
  ordered_at TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  expected_at DATE,
  created_by NUMBER REFERENCES staff(staff_id),
  notes VARCHAR2(2000),
  created_at TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  updated_at TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL
);

CREATE TABLE purchase_order_items (
  purchase_order_item_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  purchase_order_id NUMBER NOT NULL REFERENCES purchase_orders(purchase_order_id),
  product_id NUMBER NOT NULL REFERENCES products(product_id),
  unit_id NUMBER NOT NULL REFERENCES product_units(unit_id),
  quantity_ordered NUMBER(14, 3) NOT NULL CHECK (quantity_ordered > 0),
  quantity_received NUMBER(14, 3) DEFAULT 0 NOT NULL CHECK (quantity_received >= 0),
  unit_cost NUMBER(12, 4) NOT NULL CHECK (unit_cost >= 0),
  created_at TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL
);

CREATE TABLE inventory_lots (
  inventory_lot_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  product_id NUMBER NOT NULL REFERENCES products(product_id),
  purchase_order_item_id NUMBER REFERENCES purchase_order_items(purchase_order_item_id),
  lot_number VARCHAR2(100) NOT NULL,
  expiry_date DATE,
  received_at TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  received_base_quantity NUMBER(14, 3) NOT NULL CHECK (received_base_quantity >= 0),
  remaining_base_quantity NUMBER(14, 3) NOT NULL CHECK (remaining_base_quantity >= 0),
  unit_cost_base NUMBER(12, 4) CHECK (unit_cost_base >= 0),
  created_at TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT uq_product_lot UNIQUE (product_id, lot_number)
);

CREATE TABLE sales (
  sale_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  receipt_number VARCHAR2(60) NOT NULL UNIQUE,
  customer_id NUMBER REFERENCES customers(customer_id),
  created_by NUMBER REFERENCES staff(staff_id),
  status VARCHAR2(20) DEFAULT 'PAID' NOT NULL CHECK (status IN ('PAID', 'VOID', 'REFUNDED')),
  sold_at TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  subtotal NUMBER(12, 2) NOT NULL CHECK (subtotal >= 0),
  discount_amount NUMBER(12, 2) DEFAULT 0 NOT NULL CHECK (discount_amount >= 0),
  net_sales NUMBER(12, 2) NOT NULL CHECK (net_sales >= 0),
  vat_rate NUMBER(5, 2) DEFAULT 0 NOT NULL CHECK (vat_rate >= 0),
  vat_amount NUMBER(12, 2) DEFAULT 0 NOT NULL CHECK (vat_amount >= 0),
  total_amount NUMBER(12, 2) NOT NULL CHECK (total_amount >= 0),
  created_at TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL
);

CREATE TABLE sale_items (
  sale_item_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  sale_id NUMBER NOT NULL REFERENCES sales(sale_id),
  product_id NUMBER NOT NULL REFERENCES products(product_id),
  pet_id NUMBER REFERENCES pets(pet_id),
  product_name_snapshot VARCHAR2(200) NOT NULL,
  unit_name_snapshot VARCHAR2(40) NOT NULL,
  quantity NUMBER(14, 3) NOT NULL CHECK (quantity > 0),
  base_quantity NUMBER(14, 3) NOT NULL CHECK (base_quantity >= 0),
  unit_price NUMBER(12, 2) NOT NULL CHECK (unit_price >= 0),
  unit_cost_snapshot NUMBER(12, 4) CHECK (unit_cost_snapshot >= 0),
  line_discount NUMBER(12, 2) DEFAULT 0 NOT NULL CHECK (line_discount >= 0),
  line_total NUMBER(12, 2) NOT NULL CHECK (line_total >= 0),
  created_at TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL
);

CREATE TABLE sale_lot_allocations (
  allocation_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  sale_item_id NUMBER NOT NULL REFERENCES sale_items(sale_item_id),
  inventory_lot_id NUMBER NOT NULL REFERENCES inventory_lots(inventory_lot_id),
  base_quantity NUMBER(14, 3) NOT NULL CHECK (base_quantity > 0),
  unit_cost_snapshot NUMBER(12, 4) CHECK (unit_cost_snapshot >= 0),
  created_at TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL
);

CREATE TABLE sale_payments (
  payment_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  sale_id NUMBER NOT NULL REFERENCES sales(sale_id),
  payment_method VARCHAR2(20) NOT NULL CHECK (payment_method IN ('CASH', 'PROMPTPAY')),
  amount NUMBER(12, 2) NOT NULL CHECK (amount >= 0),
  paid_at TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL
);

CREATE TABLE inventory_movements (
  inventory_movement_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  inventory_lot_id NUMBER NOT NULL REFERENCES inventory_lots(inventory_lot_id),
  movement_type VARCHAR2(20) NOT NULL CHECK (movement_type IN ('RECEIVE', 'SALE', 'WASTE', 'CLINIC_USE', 'ADJUST', 'RETURN')),
  base_quantity NUMBER(14, 3) NOT NULL CHECK (base_quantity > 0),
  reference_type VARCHAR2(30),
  reference_id VARCHAR2(80),
  reason VARCHAR2(500),
  created_by NUMBER REFERENCES staff(staff_id),
  created_at TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL
);

CREATE TABLE clinic_settings (
  settings_id NUMBER DEFAULT 1 PRIMARY KEY CHECK (settings_id = 1),
  settings_json CLOB NOT NULL,
  updated_by NUMBER REFERENCES staff(staff_id),
  updated_at TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL
);

CREATE TABLE audit_logs (
  audit_log_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  staff_id NUMBER REFERENCES staff(staff_id),
  action VARCHAR2(80) NOT NULL,
  entity_name VARCHAR2(80),
  entity_id NUMBER,
  details CLOB,
  created_at TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL
);

CREATE INDEX ix_pets_customer ON pets(customer_id);
CREATE INDEX ix_products_category ON products(category_id);
CREATE INDEX ix_po_supplier_status ON purchase_orders(supplier_id, status);
CREATE INDEX ix_inventory_product_expiry ON inventory_lots(product_id, expiry_date);
CREATE INDEX ix_inventory_remaining ON inventory_lots(remaining_base_quantity);
CREATE INDEX ix_sales_sold_at ON sales(sold_at);
CREATE INDEX ix_sales_customer ON sales(customer_id, sold_at);
CREATE INDEX ix_sale_items_product ON sale_items(product_id, sale_id);
CREATE INDEX ix_audit_created_at ON audit_logs(created_at);
